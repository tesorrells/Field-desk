import assert from 'node:assert/strict';
import {collectionSchema,newQuestion,newRequirement,evidenceSnapshot,requirementFlags,questionNeedsAttention,unlinkQuestionArea,detachEvidence} from '../lib/collection.ts';
import {removeNaiLinks} from '../lib/nais.ts';
const e=evidenceSnapshot({id:'source-1',name:'Closure report',source:'Example',date:'2026-10-07'},'Source');
const r={...newRequirement(),task:'Check the closure notice',source:'Official closure feed',naiIds:['area-1'],neededBy:'2026-10-07',reviewOn:'2026-10-08',evidenceIds:[e.id]};
const q={...newQuestion(),naiIds:['area-1'],evidence:[e],requirements:[r]};
const {requirements,...legacy}=q;
assert.deepEqual(collectionSchema.parse({purpose:'',questions:[legacy]}).questions[0].requirements,[]);
assert.deepEqual(collectionSchema.parse(JSON.parse(JSON.stringify({purpose:'',questions:[q]}))).questions[0],q);
assert.deepEqual(requirementFlags(r,'2026-10-08'),{overdue:true,reviewDue:true,gap:false});
assert.deepEqual(requirementFlags({...r,status:'Answered'},'2026-10-08'),{overdue:false,reviewDue:true,gap:false});
assert.deepEqual(requirementFlags({...r,status:'Retired',source:''},'2026-10-08'),{overdue:false,reviewDue:false,gap:false});
assert.equal(questionNeedsAttention({...q,status:'Answered'},'2026-10-08'),true);
assert.equal(requirementFlags({...r,source:'',neededBy:'',naiIds:[]},'2026-10-07').gap,true);
for(const bad of [{...r,neededBy:'2026-02-30'},{...r,naiIds:['missing-area']},{...r,evidenceIds:['missing-evidence']}])assert.equal(collectionSchema.safeParse({purpose:'',questions:[{...q,requirements:[bad]}]}).success,false);
assert.equal(collectionSchema.safeParse({purpose:'',questions:[{...q,requirements:[r,r]}]}).success,false);
const unlinked=unlinkQuestionArea(q,'area-1');
assert.deepEqual(unlinked.naiIds,[]);
assert.deepEqual(unlinked.requirements[0].naiIds,[]);
assert.deepEqual(removeNaiLinks([q],'area-1')[0],unlinked);
const detached=detachEvidence(q,e.id);
assert.deepEqual(detached.evidence,[]);
assert.deepEqual(detached.requirements[0].evidenceIds,[]);
assert.equal(detached.requirements[0].task,r.task);
assert.deepEqual(q.requirements[0].evidenceIds,[e.id]);
console.log('Requirement checks passed: legacy defaults, persistence, deadlines, retired checks, gaps, invalid references, and unlinking without losing results.');
