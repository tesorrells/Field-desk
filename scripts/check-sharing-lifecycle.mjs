import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {restorePortfolio,emptyContext} from '../lib/locations.ts';
import {createSharedGroup,stageContributions,withdrawSharedContribution,sharedLifecycle,sharedMapRecords,makeSharedPackage,parseSharedPackage,previewSharedMerge} from '../lib/sharing.ts';
import {sharedRecordSchema} from '../lib/sharing-schema.ts';
import {needsSharedAttention} from '../lib/sharing-changes.ts';
import {makeBackup,parseBackup} from '../lib/backup.ts';
import {loadSigningIdentity,bindSigningIdentity,signSavedPackage} from '../lib/signing-identity.mjs';
import {verifySignedPackage} from '../lib/sharing-auth.ts';
import {isOlderStudyWrite} from '../lib/study-schema.ts';
let sam=createSharedGroup(restorePortfolio({...emptyContext(),notes:[{id:'fixture',name:'Bridge approach',lat:40,lng:-105,category:'Field',source:'Fixture',detail:'Needs inspection'}]}),'Fixture lifecycle','Sam');
const gid=sam.sharing.groups[0].id;
sam=stageContributions(sam,gid,['note:fixture']);
const original=sam.sharing.groups[0].records[0],rid=original.id,first=original.revisions[0].id;
let john=createSharedGroup(restorePortfolio(emptyContext()),'Private John group','John');
john=previewSharedMerge(john,makeSharedPackage(sam,gid,[rid]),'home').next;
assert.throws(()=>withdrawSharedContribution(john,gid,rid,'Not mine'),/origin contributor/);
assert.throws(()=>withdrawSharedContribution(sam,gid,rid,' '));
sam=withdrawSharedContribution(sam,gid,rid,'Inspection disproved the location');
const withdrawn=sam.sharing.groups[0].records[0];
assert.equal(withdrawn.revisions.length,2);assert.deepEqual(withdrawn.revisions[0],original.revisions[0]);
assert(sharedLifecycle(withdrawn).withdrawn);assert.equal(sharedMapRecords(sam).length,0);
assert.throws(()=>withdrawSharedContribution(sam,gid,rid,'Again'),/already withdrawn/);
john=previewSharedMerge(john,makeSharedPackage(sam,gid,[rid]),'home').next;
const received=john.sharing.groups.find(g=>g.id===gid);
assert.equal(received.selected[rid],first,'Import retains chosen older revision');
assert.equal(sharedMapRecords(john).length,0,'Withdrawal hides pin even when the recipient selected an old version');
assert(needsSharedAttention(received.records[0],first));
assert.equal(makeSharedPackage(john,gid,[rid],crypto.randomUUID()).records.length,0,'Withdrawal never bridges Sam to Tim');
assert.deepEqual(parseBackup(JSON.stringify(makeBackup(john,[]))).backup.study,john);
assert(isOlderStudyWrite(16,17));assert.equal(john.schemaVersion,18);
sam=stageContributions({...sam,notes:sam.notes.map(n=>({...n,detail:'Corrected approach location'}))},gid,['note:fixture'],'Corrected after field inspection');
const corrected=sam.sharing.groups[0].records[0];
assert(!sharedLifecycle(corrected).withdrawn);assert.equal(sharedLifecycle(corrected).latest.notice.reason,'Corrected after field inspection');
assert.equal(corrected.revisions.length,3);assert.equal(sharedMapRecords(sam).length,1);
const reordered={...corrected,revisions:[...corrected.revisions].reverse()};
assert.equal(sharedLifecycle(reordered).latest.id,sharedLifecycle(corrected).latest.id,'Lifecycle does not depend on array order');
const bad=structuredClone(withdrawn);bad.revisions[1].payload.detail='Changed during withdrawal';assert(!sharedRecordSchema.safeParse(bad).success);
const missing=structuredClone(withdrawn);missing.revisions[1].notice.replacesRevisionId=crypto.randomUUID();assert(!sharedRecordSchema.safeParse(missing).success);
const root=await mkdtemp(path.join(tmpdir(),'field-desk-lifecycle-'));
try{
 const key=await loadSigningIdentity(root);await bindSigningIdentity(root,key,sam.sharing.member);
 const signed=await signSavedPackage(sam,gid,[rid],john.sharing.member.id,key),parsed=parseSharedPackage(JSON.stringify(signed));
 await verifySignedPackage(parsed);john=previewSharedMerge(john,parsed,'home').next;
 assert.equal(john.sharing.groups.find(g=>g.id===gid).records[0].revisions.length,3);
 const altered=structuredClone(signed);altered.records[0].revisions.at(-1).notice.reason='Altered explanation';
 await assert.rejects(()=>verifySignedPackage(altered),/invalid/);
}finally{
 if(!root.startsWith(path.resolve(tmpdir())+path.sep)||!path.basename(root).startsWith('field-desk-lifecycle-'))throw Error('Unexpected fixture path');
 await rm(root,{recursive:true,force:true});
}
console.log('Sharing lifecycle passed: origin-only notices, retained immutable history, signature tamper rejection, chosen revision preservation, withdrawn map exclusion, correction restoration, order independence, pairwise isolation and v17 backup/migration.');
